"""Read-only local data verification runner for Contract v2 and v1.

Executes assertions compiled by `truequery.assertions` against local data
files (CSV, JSONL, JSON, Parquet) and local databases (`.duckdb`, `.sqlite`,
`.sqlite3`, `.db`).

Safety guarantees (PLAN-0.2 §3):
1. Only SQL AST statements generated by `truequery.assertions` are executed
   (verified with `assert_single_select`).
2. DuckDB connections for files expand globs in Python, verify every file
   stays inside the project root or declared base, set
   `autoinstall_known_extensions = false`, `autoload_known_extensions = false`,
   `allowed_paths = [<exact resolved files>]`,
   `enable_external_access = false`, and `lock_configuration = true`.
3. DuckDB connections for `.duckdb` files connect directly with
   `duckdb.connect(real_db_path, read_only=True)`, set `allowed_paths = []`,
   `enable_external_access = false`, and `lock_configuration = true`.
4. SQLite connections build their URI via
   `pathlib.Path(real_db_path).resolve().as_uri() + "?mode=ro"` (safe when `#`
   or special characters appear in paths) and set `PRAGMA query_only = ON;`.
5. Untrusted paths in data (`path_resolves`, `exists_per_status`,
   `size_matches_disk`) are resolved with `os.path.realpath` and checked with
   `os.path.commonpath([real_base, real_target]) == real_base` before any
   `os.stat()` or `os.path.exists()` call.
6. CSV and JSONL columns are read as raw text (`VARCHAR`) so DuckDB's sniffer
   cannot coerce mixed `Z`/naive timestamps or rounded `1.07` sizes.
7. Columns marked `pii: true` never emit sample key values in reports or
   `.truequery/evidence.jsonl`.
8. Draft contracts (`status: draft` or unconfirmed grain) tag every assertion,
   finding, summary, and evidence entry with their draft provenance.
"""

