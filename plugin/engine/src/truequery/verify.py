class VerificationError(ValueError):
    """Raised when a data source cannot be safely resolved or opened."""


class DuckDBMissingError(RuntimeError):
    """Raised when DuckDB is required to verify a dataset but is not installed."""


# The lowest DuckDB with every lockdown setting the runner relies on
# (`allowed_paths` arrived in 1.2.0). The `data` extra in pyproject.toml,
# `truequery setup data` and the plugin launcher all use this spec.
DUCKDB_MIN_VERSION = (1, 2, 0)
DUCKDB_SPEC = "duckdb>=1.2.0"

EVIDENCE_FILE = "evidence.jsonl"
# One verify run writes one line per assertion (about 0.5 KB each). When
# the file passes this size it is moved to `evidence.jsonl.1` (replacing
# the previous one), so the log never takes more than about twice this.
MAX_EVIDENCE_BYTES = 5 * 1024 * 1024


def _version_tuple(text: str) -> tuple[int, ...]:
    parts = []
    for bit in re.split(r"[.+-]", text):
        if not bit.isdigit():
            break
        parts.append(int(bit))
    return tuple(parts)


def duckdb_status() -> dict[str, Any]:
    """Whether the data reader is usable, without importing it:
    `{"installed": bool, "version": str | None, "too_old": bool}`."""
    import importlib.util
    try:
        found = importlib.util.find_spec("duckdb") is not None
    except (ImportError, ValueError):
        found = False
    if not found:
        return {"installed": False, "version": None, "too_old": False}
    version = None
    try:
        from importlib.metadata import PackageNotFoundError, version as _v
        try:
            version = _v("duckdb")
        except PackageNotFoundError:
            version = None
    except ImportError:  # pragma: no cover - stdlib on 3.11+
        version = None
    too_old = bool(version) and _version_tuple(version) < DUCKDB_MIN_VERSION
    return {"installed": not too_old, "version": version, "too_old": too_old}


def needs_duckdb(contract: dict) -> bool:
    """True when verifying `contract` reads data through DuckDB (data
    files, or a `.duckdb` database). SQLite files need only the stdlib."""
    if (contract.get("kind") or "table") == "files":
        return True
    loc = contract.get("location") if isinstance(contract.get("location"), dict) else {}
    return str(loc.get("database") or "").lower().endswith(".duckdb")


def has_local_data(contract: dict) -> bool:
    """True when the contract points at data TrueQuery can read here: files,
    or a table with `location.database`."""
    if (contract.get("kind") or "table") == "files":
        return True
    loc = contract.get("location") if isinstance(contract.get("location"), dict) else {}
    return bool(loc.get("database"))


def local_data_contracts(contracts: dict) -> list[str]:
    """Names of the valid contracts whose data `verify` can read here."""
    return sorted(str(c.get("dataset") or c.get("table"))
                  for c in contracts.values() if has_local_data(c))


def _import_duckdb():
    try:
        import duckdb
    except ImportError as exc:
        raise DuckDBMissingError(
            "the data reader isn't installed. Run: truequery setup data"
        ) from exc
    version = getattr(duckdb, "__version__", "") or ""
    if version and _version_tuple(version) < DUCKDB_MIN_VERSION:
        raise DuckDBMissingError(
            f"the data reader is too old (DuckDB {version}; TrueQuery needs "
            f"{DUCKDB_SPEC}). Run: truequery setup data"
        )
    return duckdb


def append_evidence(project_root: str, records: list[dict[str, Any]],
                    run_at: str | None = None) -> str | None:
    """Append `records` to `<root>/.truequery/evidence.jsonl` and return
    its path. Rotates to `evidence.jsonl.1` past `MAX_EVIDENCE_BYTES`, and
    keeps the log out of git with `.truequery/.gitignore`."""
    if not records:
        return None
    ev_dir = os.path.join(project_root, ".truequery")
    os.makedirs(ev_dir, exist_ok=True)
    _ignore_evidence(ev_dir)
    ev_path = os.path.join(ev_dir, EVIDENCE_FILE)
    try:
        if os.path.getsize(ev_path) > MAX_EVIDENCE_BYTES:
            os.replace(ev_path, ev_path + ".1")
    except OSError:
        pass
    if run_at is None:
        run_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    with open(ev_path, "a", encoding="utf-8") as handle:
        for rec in records:
            handle.write(json.dumps({**rec, "run_at": run_at},
                                    sort_keys=True) + "\n")
    return ev_path


_EVIDENCE_IGNORES = ("evidence.jsonl", "evidence.jsonl.1")


def _ignore_evidence(ev_dir: str) -> None:
    path = os.path.join(ev_dir, ".gitignore")
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        text = None
    if text is None:
        text = ("# TrueQuery session state (ignores.json is meant to be "
                "committed)\nsession.json\nhook.log\n")
    missing = [n for n in _EVIDENCE_IGNORES if n not in text.split("\n")]
    if not missing:
        return
    if text and not text.endswith("\n"):
        text += "\n"
    try:
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text + "".join(n + "\n" for n in missing))
    except OSError:
        pass


def _sql_string_literal(val: str) -> str:
    return "'" + val.replace("'", "''") + "'"


def open_duckdb_for_files(file_paths: list[str]):
    """Open an in-memory DuckDB connection locked to the exact `file_paths`."""
    duckdb = _import_duckdb()
    resolved = [os.path.realpath(p) for p in file_paths]
    paths_sql = "[" + ", ".join(_sql_string_literal(p) for p in resolved) + "]"
    con = duckdb.connect(":memory:")
    con.execute("SET autoinstall_known_extensions = false;")
    con.execute("SET autoload_known_extensions = false;")
    con.execute(f"SET allowed_paths = {paths_sql};")
    con.execute("SET enable_external_access = false;")
    con.execute("SET lock_configuration = true;")
    return con


def open_duckdb_database(db_path: str):
    """Open a `.duckdb` database file in read-only mode and lock configuration."""
    duckdb = _import_duckdb()
    real_db = os.path.realpath(db_path)
    if not os.path.isfile(real_db):
        raise VerificationError(f"database file does not exist: {db_path}")
    con = duckdb.connect(real_db, read_only=True)
    con.execute("SET autoinstall_known_extensions = false;")
    con.execute("SET autoload_known_extensions = false;")
    con.execute("SET allowed_paths = [];")
    con.execute("SET enable_external_access = false;")
    con.execute("SET lock_configuration = true;")
    return con


def _sqlite_wal_closed(real_db: str) -> bool:
    """True for a database in WAL mode that nobody has open: the header says
    WAL (bytes 18-19 are 2) and there is no `-wal` file beside it."""
    try:
        with open(real_db, "rb") as fh:
            header = fh.read(20)
    except OSError:
        return False
    return (len(header) == 20 and header[:16] == b"SQLite format 3\x00"
            and header[18] == 2 and header[19] == 2
            and not os.path.lexists(real_db + "-wal"))


def sqlite_readonly_uri(db_path: str) -> str:
    """Build a read-only SQLite URI safe on paths containing `#`, spaces, etc.

    A WAL-mode database opened with only `mode=ro` gets a `-shm` and a `-wal`
    file created beside it, which stay. When no `-wal` file exists nobody has
    the database open, so it's opened `immutable=1`: no locks, no side files.
    (If a writer opens it during the check, the result can be stale; the file
    is still never written.) With a `-wal` file there, someone has it open
    (or it wasn't closed cleanly): `mode=ro` reads it through the files that
    are already there.
    """
    real_db = Path(os.path.realpath(db_path)).resolve()
    query = "?mode=ro"
    if _sqlite_wal_closed(str(real_db)):
        query += "&immutable=1"
    return real_db.as_uri() + query


def open_sqlite_readonly(db_path: str) -> sqlite3.Connection:
    """Open a SQLite database in read-only mode via RFC-3986 URI + `query_only`."""
    real_db = os.path.realpath(db_path)
    if not os.path.isfile(real_db):
        raise VerificationError(f"database file does not exist: {db_path}")
    uri = sqlite_readonly_uri(real_db)
    con = sqlite3.connect(uri, uri=True)
    con.execute("PRAGMA query_only = ON;")
    return con


def resolve_base_dir(
    base_name: str | None,
    bases: dict | None,
    project_root: str,
) -> str:
    """Resolve `base_name` against `DATA.md` `bases:` (or `project_root` if None)."""
    root_real = os.path.realpath(project_root)
    if not base_name:
        return root_real
    norm_bases = contract_v2.validate_bases(bases or {})
    if base_name not in norm_bases:
        raise VerificationError(
            f"undeclared base {base_name!r} (declare it under `bases:` in "
            "DATA.md tq-config)")
    spec = norm_bases[base_name]
    raw_dir = None
    if spec.get("env"):
        raw_dir = os.environ.get(spec["env"])
    if not raw_dir:
        raw_dir = spec.get("default")
    if not raw_dir:
        raise VerificationError(
            f"base {base_name!r} has no path (set ${spec.get('env')} or "
            "provide a default in DATA.md)"
        )
    if os.path.isabs(raw_dir):
        return os.path.realpath(raw_dir)
    return os.path.realpath(os.path.join(root_real, raw_dir))


PATH_CACHE_LIMIT = 100_000  # folders remembered per check


def resolve_path_within_base(row_path: str, real_base: str,
                             cache: dict | None = None) -> str | None:
    """Resolve `row_path` under `real_base` and verify it never escapes `real_base`.

    Returns the resolved `real_target` string if safe, or `None` if `row_path`
    is empty, contains NUL, is absolute, starts with `~` or a Windows drive, or
    escapes `real_base` via `..` or a symlink at any path prefix.

    `cache` (one dict per check) remembers the folders already resolved, so a
    log of a million paths in a few hundred folders resolves each folder once.
    """
    if not isinstance(row_path, str):
        return None
    cleaned = row_path.strip()
    if not cleaned or "\x00" in cleaned:
        return None
    norm = cleaned.replace("\\", "/")
    if (norm.startswith("/") or norm.startswith("~")
            or re.match(r"^[A-Za-z]:", norm)):
        return None
    parts = [p for p in norm.split("/") if p and p != "."]
    if not parts or ".." in parts or "~" in parts:
        return None

    if cache is None:
        cache = {}
    base_real = cache.get(("base", real_base))
    if base_real is None:
        base_real = cache[("base", real_base)] = os.path.realpath(real_base)
    cur: str | None = base_real
    for depth, part in enumerate(parts):
        last = depth == len(parts) - 1
        key = (base_real, tuple(parts[:depth + 1]))
        if not last and key in cache:
            cur = cache[key]
            if cur is None:
                return None
            continue
        cur = _resolve_one(base_real, cur, part)
        if not last:
            if len(cache) > PATH_CACHE_LIMIT:  # bounded memory
                cache.clear()
                cache[("base", real_base)] = base_real
            cache[key] = cur
        if cur is None:
            return None
    return cur


def _resolve_one(base_real: str, parent_real: str, part: str) -> str | None:
    """`parent_real/part` resolved, or None when it leaves `base_real`.
    `parent_real` is already resolved, so on POSIX only a link needs
    resolving; Windows (junctions) always goes through realpath."""
    candidate = os.path.join(parent_real, part)
    if os.name == "posix" and not os.path.islink(candidate):
        return candidate
    resolved = os.path.realpath(candidate)
    try:
        if os.path.commonpath([base_real, resolved]) != base_real:
            return None
    except ValueError:
        return None
    return resolved


def expand_contract_files(
    contract: dict,
    bases: dict | None,
    project_root: str,
) -> tuple[str, list[str]]:
    """Expand `location.path` for a `kind: files` contract safely inside its base.

    Returns `(real_base, sorted_resolved_files)`. Raises `VerificationError` if
    the glob or any matched file escapes `real_base`.
    """
    loc = contract.get("location")
    if not isinstance(loc, dict) or not loc.get("path"):
        raise VerificationError("contract has no `location.path`")
    rel_glob = str(loc["path"])
    if not contract_v2._is_safe_rel_path(rel_glob):
        raise VerificationError(
            f"location.path {rel_glob!r} must be a relative path inside the "
            "project or declared base")
    real_base = resolve_base_dir(loc.get("base"), bases, project_root)
    pattern = os.path.join(real_base, rel_glob)
    matched = sorted(glob.glob(pattern, recursive=True))
    safe_files: list[str] = []
    for path in matched:
        real_p = os.path.realpath(path)
        try:
            inside = os.path.commonpath([real_base, real_p]) == real_base
        except ValueError:
            inside = False
        if not inside:
            where = loc.get("base") or "the project folder"
            raise VerificationError(
                f"{P._rel(os.path.abspath(path), os.path.realpath(project_root))} "
                f"points outside {where} (a link?), so nothing was read")
        if os.path.isfile(real_p):
            safe_files.append(real_p)
    return real_base, sorted(set(safe_files))


def check_size_matches_disk(
    raw_size_text: str,
    actual_bytes: int,
    declared_unit: str,
) -> dict[str, Any]:
    """Compare a logged size string against `actual_bytes` (`os.stat().st_size`).

    Allows half a unit in the last printed digit:
      tolerance = 0.5 * 10^(-d) * unit_factor
    When a mismatch occurs on a unit with a decimal/binary twin (`GiB` <-> `GB`,
    `MiB` <-> `MB`, `KiB` <-> `KB`, `TiB` <-> `TB`), tests the twin unit with
    the same half-ULP rule so `1.07` GB logged under a `GiB` contract reports
    `matched_twin_unit = "GB"`.
    """
    if declared_unit not in UNIT_FACTORS:
        raise ValueError(f"unsupported size unit {declared_unit!r}")
    text = str(raw_size_text).strip()
    try:
        dec = Decimal(text)
    except (InvalidOperation, ValueError):
        return {
            "matches": False,
            "reason": "invalid_number",
            "matched_twin_unit": None,
        }
    if dec < 0 or not dec.is_finite():
        return {
            "matches": False,
            "reason": "negative_or_nonfinite",
            "matched_twin_unit": None,
        }

    exp_tuple = dec.as_tuple().exponent
    d = -int(exp_tuple) if isinstance(exp_tuple, int) and exp_tuple < 0 else 0
    half_ulp = Decimal("0.5") * (Decimal(10) ** (-d))
    actual_dec = Decimal(actual_bytes)

    factor = Decimal(UNIT_FACTORS[declared_unit])
    expected = dec * factor
    tol = Decimal("0.5") if declared_unit == "bytes" and d == 0 else half_ulp * factor
    if abs(expected - actual_dec) <= tol:
        return {
            "matches": True,
            "reason": None,
            "matched_twin_unit": None,
        }

    twin = TWIN_UNITS.get(declared_unit)
    matched_twin = None
    if twin is not None:
        twin_factor = Decimal(UNIT_FACTORS[twin])
        twin_expected = dec * twin_factor
        twin_tol = half_ulp * twin_factor
        if abs(twin_expected - actual_dec) <= twin_tol:
            matched_twin = twin

    return {
        "matches": False,
        "reason": "twin_unit_mismatch" if matched_twin else "size_mismatch",
        "matched_twin_unit": matched_twin,
    }


def _parse_now(now: datetime | str | None) -> datetime:
    if now is None:
        return datetime.now(timezone.utc)
    if isinstance(now, datetime):
        if now.tzinfo is None:
            return now.replace(tzinfo=timezone.utc)
        return now.astimezone(timezone.utc)
    if isinstance(now, str):
        s = now.strip()
        if s.endswith(("Z", "z")):
            s = s[:-1] + "+00:00"
        dt = datetime.fromisoformat(s)
        if dt.tzinfo is None:
            return dt.replace(tzinfo=timezone.utc)
        return dt.astimezone(timezone.utc)
    raise TypeError(f"unsupported `now` value: {now!r}")


def _parse_timestamp_utc(
    raw: str,
    declared_tz: str | None = None,
) -> datetime | None:
    """Parse an ISO timestamp or date string into a UTC-aware `datetime`.

    - Explicit offsets (`Z`, `+HH:MM`, `+HHMM`, `+HH`) are converted to UTC.
    - Naive values on a `local:<zone>` column are localized with
      `zoneinfo.ZoneInfo(<zone>)` and converted to UTC; if `<zone>` is not
      available in `zoneinfo`, returns `None` (never reads a local naive value
      as UTC).
    - Naive values on `UTC`, `naive`, or undeclared `time_zone` are treated as
      UTC instants.
    """
    s = str(raw).strip()
    if not s:
        return None
    if s.endswith(("Z", "z")):
        s = s[:-1] + "+00:00"
    elif re.search(r"(?:T|\s)\d{2}:\d{2}(?::\d{2}(?:\.\d+)?)?[+-]\d{2}$", s):
        s = s + ":00"
    elif re.search(r"(?:T|\s)\d{2}:\d{2}(?::\d{2}(?:\.\d+)?)?[+-]\d{4}$", s):
        s = s[:-2] + ":" + s[-2:]
    try:
        dt = datetime.fromisoformat(s)
    except ValueError:
        return None
    if dt.tzinfo is None:
        if isinstance(declared_tz, str) and declared_tz.startswith("local:"):
            zone_name = declared_tz.split(":", 1)[1].strip()
            if not zone_name:
                return None
            try:
                from zoneinfo import ZoneInfo
                tz_obj = ZoneInfo(zone_name)
            except Exception:
                return None
            return dt.replace(tzinfo=tz_obj).astimezone(timezone.utc)
        return dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


def _zoneinfo_available(zone_name: str) -> bool:
    try:
        from zoneinfo import ZoneInfo
        ZoneInfo(zone_name)
        return True
    except Exception:
        return False


def _parse_duration(duration_str: str) -> timedelta:
    m = _DURATION_PARSE_RE.match(str(duration_str).strip())
    if not m:
        raise ValueError(f"invalid duration {duration_str!r}")
    amount = int(m.group(1))
    unit = m.group(2)
    if unit == "ms":
        return timedelta(milliseconds=amount)
    if unit == "s":
        return timedelta(seconds=amount)
    if unit == "min":
        return timedelta(minutes=amount)
    if unit == "h":
        return timedelta(hours=amount)
    if unit == "d":
        return timedelta(days=amount)
    raise ValueError(f"invalid duration unit {unit!r}")


def _format_sample_key(row_keys: tuple[Any, ...]) -> Any:
    if not row_keys:
        return None
    if len(row_keys) == 1:
        return str(row_keys[0]) if row_keys[0] is not None else None
    return [str(k) if k is not None else None for k in row_keys]


def _setup_duckdb_files_view(
    con,
    view_name: str,
    fmt: str,
    files: list[str],
    contract: dict,
) -> dict[str, str]:
    """Create TEMP VIEW `view_name` over `files` in `con` and return `{col_lower: type}`."""
    files_sql = "[" + ", ".join(_sql_string_literal(f) for f in files) + "]"
    quoted_view = exp.table_(exp.to_identifier(view_name, quoted=True)).sql(dialect="duckdb")
    if fmt == "csv":
        con.execute(
            f"CREATE OR REPLACE TEMP VIEW {quoted_view} AS "
            f"SELECT * FROM read_csv({files_sql}, all_varchar=true);"
        )
    elif fmt in ("jsonl", "json"):
        desc = con.execute(
            f"DESCRIBE SELECT * FROM read_json({files_sql}, auto_detect=true);"
        ).fetchall()
        col_names: list[str] = []
        seen_lower: set[str] = set()
        for r in desc:
            cname = str(r[0])
            if cname.lower() not in seen_lower:
                seen_lower.add(cname.lower())
                col_names.append(cname)
        for key_entry in contract.get("keys") or []:
            for kcol in (key_entry if isinstance(key_entry, list) else [key_entry]):
                cleaned_k = A._clean_ident_part(str(kcol))
                if cleaned_k.lower() not in seen_lower:
                    seen_lower.add(cleaned_k.lower())
                    col_names.append(cleaned_k)
        for kcol in contract.get("columns") or {}:
            cleaned_k = A._clean_ident_part(str(kcol))
            if cleaned_k.lower() not in seen_lower:
                seen_lower.add(cleaned_k.lower())
                col_names.append(cleaned_k)
        col_map = "{" + ", ".join(
            f"{_sql_string_literal(c)}: 'VARCHAR'" for c in col_names
        ) + "}"
        con.execute(
            f"CREATE OR REPLACE TEMP VIEW {quoted_view} AS "
            f"SELECT * FROM read_json({files_sql}, columns={col_map});"
        )
    elif fmt == "parquet":
        con.execute(
            f"CREATE OR REPLACE TEMP VIEW {quoted_view} AS "
            f"SELECT * FROM read_parquet({files_sql});"
        )
    else:
        raise VerificationError(f"unsupported file format {fmt!r}")

    desc_rows = con.execute(f"DESCRIBE {quoted_view};").fetchall()
    return {str(r[0]).lower(): str(r[1]).upper() for r in desc_rows}


def _describe_relation_columns_and_types(
    con,
    dialect: str,
    relation: str,
) -> tuple[tuple[str, ...], dict[str, str]]:
    quoted_rel = A._quote_table(relation).sql(dialect=dialect)
    if dialect == "duckdb":
        rows = con.execute(f"DESCRIBE {quoted_rel};").fetchall()
        col_order = tuple(str(r[0]) for r in rows)
        type_map = {str(r[0]).lower(): str(r[1]).upper() for r in rows}
        return col_order, type_map
    # SQLite: PRAGMA table_info
    table_only = A._clean_ident_part(relation.split(".")[-1]).replace('"', '""')
    rows = con.execute(f'PRAGMA table_info("{table_only}");').fetchall()
    col_order = tuple(str(r[1]) for r in rows)
    type_map = {str(r[1]).lower(): str(r[2]).upper() for r in rows}
    return col_order, type_map


def _describe_relation_types(con, dialect: str, relation: str) -> dict[str, str]:
    _, type_map = _describe_relation_columns_and_types(con, dialect, relation)
    return type_map


def _sample_phrase(params: dict[str, Any], rows_checked: int) -> str:
    if not params.get("sampled"):
        return ""
    order_by = params.get("sample_order_by") or "row"
    return f"in the first {rows_checked:,} rows by {order_by}"


def _execute_single_select(con, sql_text: str, dialect: str) -> list[tuple]:
    """Verify `sql_text` is a single `exp.Select` and execute it."""
    A.assert_single_select(sql_text, dialect=dialect)
    return con.execute(sql_text).fetchall()


def _run_sql_assertion(
    con,
    comp: A.CompiledAssertion,
    total_rows: int,
    physical_types: dict[str, str],
    source_format: str | None,
    now_dt: datetime,
) -> dict[str, Any]:
    params = comp.params
    prov_note = params.get("provenance_note")
    pii_redacted = bool(params.get("pii_redacted"))
    pk_len = len(params.get("key_columns") or ())
    sampled = bool(params.get("sampled"))
    s_phrase = _sample_phrase(params, total_rows)
    s_suffix = f" {s_phrase}" if s_phrase else ""

    # Special case: `tz_marker` on real native TIMESTAMP columns (Parquet and
    # DuckDB tables only; SQLite and text columns always check values).
    if comp.assertion == "tz_marker" and source_format in ("parquet", "duckdb"):
        col_name = str(comp.target)
        tz = str(params["time_zone"])
        phys = physical_types.get(col_name.lower(), "VARCHAR")
        src_col_label = (
            f"Parquet column {col_name!r}"
            if source_format == "parquet"
            else f"DuckDB table column {col_name!r}"
        )
        if phys in _NATIVE_TZ_TS_TYPES:
            if tz == "UTC":
                return {
                    "assertion": "tz_marker",
                    "target": col_name,
                    "status": "passed",
                    "rows_checked": total_rows,
                    "failed_count": 0,
                    "sample_keys": [],
                    "pii_redacted": pii_redacted,
                    "message": (
                        f"{src_col_label} has physical type {phys} (UTC){s_suffix}"
                    ),
                    "details": {"physical_type": phys, "time_zone": tz},
                    "provenance_note": prov_note,
                }
            if tz.startswith("local:"):
                return {
                    "assertion": "tz_marker",
                    "target": col_name,
                    "status": "not_verified",
                    "rows_checked": total_rows,
                    "failed_count": 0,
                    "sample_keys": [],
                    "pii_redacted": pii_redacted,
                    "message": (
                        f"{src_col_label} has {phys} type; "
                        f"cannot verify local time zone {tz!r}{s_suffix}"
                    ),
                    "details": {"physical_type": phys, "time_zone": tz},
                    "provenance_note": prov_note,
                }
            # tz == "naive" but physical type has time zone
            return {
                "assertion": "tz_marker",
                "target": col_name,
                "status": "failed",
                "rows_checked": total_rows,
                "failed_count": total_rows,
                "sample_keys": [],
                "pii_redacted": pii_redacted,
                "message": (
                    f"{src_col_label} has physical type {phys}, "
                    f"contract says naive{s_suffix}"
                ),
                "details": {"physical_type": phys, "time_zone": tz},
                "provenance_note": prov_note,
            }
        if phys in _NATIVE_NAIVE_TS_TYPES:
            if tz == "UTC":
                return {
                    "assertion": "tz_marker",
                    "target": col_name,
                    "status": "not_verified",
                    "rows_checked": total_rows,
                    "failed_count": 0,
                    "sample_keys": [],
                    "pii_redacted": pii_redacted,
                    "message": (
                        f"{src_col_label} has naive {phys} type; "
                        f"cannot verify UTC marker{s_suffix}"
                    ),
                    "details": {"physical_type": phys, "time_zone": tz},
                    "provenance_note": prov_note,
                }
            return {
                "assertion": "tz_marker",
                "target": col_name,
                "status": "passed",
                "rows_checked": total_rows,
                "failed_count": 0,
                "sample_keys": [],
                "pii_redacted": pii_redacted,
                "message": (
                    f"{src_col_label} has naive {phys} type "
                    f"(matches {tz}){s_suffix}"
                ),
                "details": {"physical_type": phys, "time_zone": tz},
                "provenance_note": prov_note,
            }

    # Special case: `freshness` — parse every non-null value in Python and take
    # the maximum of the parsed UTC instants.
    if comp.assertion == "freshness":
        col_name = str(comp.target)
        max_age_str = str(params["max_age"])
        declared_tz = params.get("time_zone")
        max_delta = _parse_duration(max_age_str)
        rows = _execute_single_select(con, comp.sql, comp.dialect)
        if not rows:
            return {
                "assertion": "freshness",
                "target": col_name,
                "status": "failed",
                "rows_checked": total_rows,
                "failed_count": 1,
                "sample_keys": [],
                "pii_redacted": True,
                "message": (
                    f"no non-null timestamps in {col_name!r} to verify "
                    f"freshness SLA <= {max_age_str}{s_suffix}"
                ),
                "details": {"max_timestamp": None, "max_age": max_age_str},
                "provenance_note": prov_note,
            }

        parsed_dts: list[datetime] = []
        unparseable_count = 0
        for (raw_val,) in rows:
            dt = _parse_timestamp_utc(str(raw_val), declared_tz=declared_tz)
            if dt is None:
                unparseable_count += 1
            else:
                parsed_dts.append(dt)

        if unparseable_count > 0:
            if (isinstance(declared_tz, str)
                    and declared_tz.startswith("local:")
                    and not _zoneinfo_available(declared_tz.split(":", 1)[1].strip())):
                zone_name = declared_tz.split(":", 1)[1].strip()
                nv_msg = (
                    f"cannot verify freshness on {col_name!r}: time zone "
                    f"{zone_name!r} is not available in zoneinfo for naive "
                    f"local timestamps{s_suffix}"
                )
            else:
                nv_msg = (
                    f"cannot verify freshness on {col_name!r}: "
                    f"{unparseable_count} value(s) could not be parsed as a "
                    f"timestamp or date{s_suffix}"
                )
            return {
                "assertion": "freshness",
                "target": col_name,
                "status": "not_verified",
                "rows_checked": total_rows,
                "failed_count": 0,
                "sample_keys": [],
                "pii_redacted": True,
                "message": nv_msg,
                "details": {
                    "unparseable_count": unparseable_count,
                    "max_age": max_age_str,
                },
                "provenance_note": prov_note,
            }

        max_dt = max(parsed_dts)
        age = now_dt - max_dt
        passed = age <= max_delta
        # A column marked pii: say whether it's fresh, never its value (or
        # the age, which gives the value back with --now).
        hidden = bool(params.get("value_hidden"))
        shown = "" if hidden else f" ({max_dt.isoformat()})"
        return {
            "assertion": "freshness",
            "target": col_name,
            "status": "passed" if passed else "failed",
            "rows_checked": total_rows,
            "failed_count": 0 if passed else 1,
            "sample_keys": [],
            "pii_redacted": True,
            "message": (
                f"newest {col_name}{shown} is within "
                f"{max_age_str} of {now_dt.isoformat()}{s_suffix}"
                if passed
                else f"stale data: newest {col_name}{shown} is "
                     f"older than {max_age_str} at {now_dt.isoformat()}{s_suffix}"
            ),
            "details": {
                "max_timestamp": None if hidden else max_dt.isoformat(),
                "value_hidden": hidden,
                "checked_at": now_dt.isoformat(),
                "max_age": max_age_str,
            },
            "provenance_note": prov_note,
        }

    # Standard SQL count + sample assertions (`not_null`, `unique`, `accepted_values`, `tz_marker`)
    # Private by default (DESIGN §5): report counts and at most 5 failing key values,
    # never non-key column values, and never keys when `pii_redacted` is True.
    cnt_rows = _execute_single_select(con, comp.count_sql, comp.dialect)
    counts = list(cnt_rows[0]) if cnt_rows else []
    counts += [None] * (3 - len(counts))
    failed_count = int(counts[0] or 0)
    # values the check looked at (not_null and unique look at every row)
    compared = int(counts[1] or 0) if counts[1] is not None else total_rows
    empty_count = int(counts[2] or 0)
    sample_rows = (
        _execute_single_select(con, comp.sql, comp.dialect)
        if failed_count > 0 and not pii_redacted
        else []
    )

    sample_keys: list[Any] = []
    if failed_count > 0 and not pii_redacted:
        for row in sample_rows[:MAX_SAMPLE_KEYS]:
            if comp.assertion == "unique":
                kcols = params["key_columns"]
                sample_keys.append(_format_sample_key(tuple(row[:len(kcols)])))
            elif pk_len:
                sample_keys.append(_format_sample_key(tuple(row[:pk_len])))

    passed = failed_count == 0
    status = "passed" if passed else "failed"
    target_label = (
        "(" + ", ".join(comp.target) + ")"
        if isinstance(comp.target, tuple)
        else str(comp.target)
    )
    if comp.assertion == "not_null":
        if sampled:
            msg = (
                f"{target_label} is non-null {s_phrase}"
                if passed
                else f"{failed_count} null/empty value(s) in {target_label} {s_phrase}"
            )
        else:
            msg = (
                f"{target_label} is non-null across {total_rows} rows"
                if passed
                else f"{failed_count} null/empty value(s) in {target_label}"
            )
    elif comp.assertion == "unique":
        if sampled:
            if passed:
                status = "not_verified"
                msg = (
                    f"key {target_label} not verified for the whole dataset "
                    f"(no duplicates {s_phrase})"
                )
            else:
                msg = f"{failed_count} duplicate key value(s) for {target_label} {s_phrase}"
        else:
            msg = (
                f"key {target_label} unique across {total_rows} rows"
                if passed
                else f"{failed_count} duplicate key value(s) for {target_label}"
            )
    elif comp.assertion == "accepted_values":
        msg = (
            f"all values in {target_label} are declared{s_suffix}"
            if passed
            else f"{failed_count} undeclared value(s) in {target_label}{s_suffix}"
        )
    elif comp.assertion == "tz_marker":
        tz = str(params["time_zone"])
        msg = (
            f"timestamps in {target_label} match {tz}{s_suffix}"
            if passed
            else f"{failed_count} timestamp(s) in {target_label} violate "
                 f"declared time_zone {tz!r}{s_suffix}"
        )
    else:
        msg = f"{comp.assertion} on {target_label}: {'passed' if passed else 'failed'}{s_suffix}"

    return {
        "assertion": comp.assertion,
        "target": list(comp.target) if isinstance(comp.target, tuple) else comp.target,
        "status": status,
        "rows_checked": total_rows,
        "failed_count": failed_count,
        "sample_keys": sample_keys,
        "pii_redacted": pii_redacted,
        "message": msg,
        "details": ({"compared": compared, "empty_count": empty_count}
                    if comp.assertion == "accepted_values"
                    else {"compared": compared}),
        "provenance_note": prov_note,
    }


def _run_filesystem_assertion(
    con,
    comp: A.CompiledAssertion,
    total_rows: int,
    bases: dict | None,
    project_root: str,
) -> dict[str, Any]:
    params = comp.params
    prov_note = params.get("provenance_note")
    pii_redacted = bool(params.get("pii_redacted"))
    pk_len = len(params.get("key_columns") or ())
    rel_to = params.get("relative_to")
    base_label = str(rel_to) if rel_to else "project_root"
    real_base = resolve_base_dir(rel_to, bases, project_root)
    path_cache: dict = {}  # folders resolved once per check
    rows = _execute_single_select(con, comp.sql, comp.dialect)
    s_phrase = _sample_phrase(params, total_rows)
    s_suffix = f" {s_phrase}" if s_phrase else ""

    if comp.assertion == "path_resolves":
        col_name = str(comp.target)
        status_col = params.get("status_column")
        status_means: dict[str, str] = params.get("status_means") or {}
        if not os.path.isdir(real_base):
            return {
                "assertion": "path_resolves",
                "target": col_name,
                "status": "failed",
                "rows_checked": len(rows),
                "failed_count": len(rows) or 1,
                "sample_keys": [],
                "pii_redacted": pii_redacted,
                "message": (
                    f"declared base {base_label!r} ({real_base}) does not exist{s_suffix}"
                ),
                "details": {"base": base_label, "real_base": real_base},
                "provenance_note": prov_note,
            }
        failed_count = 0
        escaped_count = 0
        wrong_base_count = 0
        present_checked = 0
        present_existing = 0
        present_unflagged_keys: list[Any] = []
        sample_keys: list[Any] = []
        paths_compared = 0
        for row in rows:
            raw_path = row[pk_len]
            if raw_path is None or not str(raw_path).strip():
                continue
            paths_compared += 1
            status_val = (
                str(row[pk_len + 1])
                if status_col and len(row) > pk_len + 1 and row[pk_len + 1] is not None
                else None
            )
            means = status_means.get(status_val) if status_val is not None else None
            # Step 1: containment check — NEVER stat/exists a path that escapes real_base
            real_target = resolve_path_within_base(str(raw_path), real_base, path_cache)
            if real_target is None:
                failed_count += 1
                escaped_count += 1
                if pk_len and not pii_redacted and len(sample_keys) < MAX_SAMPLE_KEYS:
                    sample_keys.append(_format_sample_key(tuple(row[:pk_len])))
                continue
            # Step 2: for paths without a status lifecycle (or when zero `present`
            # rows exist under `real_base`), flag wrong base resolution.
            if status_col is None:
                if not os.path.exists(real_target):
                    failed_count += 1
                    wrong_base_count += 1
                    if pk_len and not pii_redacted and len(sample_keys) < MAX_SAMPLE_KEYS:
                        sample_keys.append(_format_sample_key(tuple(row[:pk_len])))
            elif means == "present":
                present_checked += 1
                if os.path.exists(real_target):
                    present_existing += 1
                else:
                    present_unflagged_keys.append(
                        _format_sample_key(tuple(row[:pk_len])) if pk_len else None
                    )

        # If `rel_to` was declared and `present` rows were checked and NOT ONE
        # resolved under `real_base`, the base directory itself does not match
        # the data's paths.
        if rel_to and present_checked > 0 and present_existing == 0 and present_unflagged_keys:
            failed_count += len(present_unflagged_keys)
            wrong_base_count += len(present_unflagged_keys)
            if pk_len and not pii_redacted:
                for k in present_unflagged_keys:
                    if len(sample_keys) < MAX_SAMPLE_KEYS:
                        sample_keys.append(k)

        passed = failed_count == 0
        msg = (
            f"paths in {col_name!r} resolve under {base_label}{s_suffix}"
            if passed
            else f"{failed_count} path(s) in {col_name!r} escape or do not "
                 f"resolve under base {base_label!r}{s_suffix}"
        )
        return {
            "assertion": "path_resolves",
            "target": col_name,
            "status": "passed" if passed else "failed",
            "rows_checked": len(rows),
            "failed_count": failed_count,
            "sample_keys": sample_keys,
            "pii_redacted": pii_redacted,
            "message": msg,
            "details": {
                "base": base_label,
                "escaped_count": escaped_count,
                "unresolved_base_count": wrong_base_count,
                "compared": paths_compared,
            },
            "provenance_note": prov_note,
        }

    if comp.assertion == "exists_per_status":
        col_name = str(comp.target)
        status_means = params.get("status_means") or {}
        failed_count = 0
        present_missing = 0
        unexpected_absent = 0
        escaped_count = 0
        absent_expected_count = 0
        absent_expected_statuses: set[str] = set()
        todo_statuses: set[str] = set()
        todo_rows = 0
        present_compared = 0
        failure_compared = 0
        sample_keys = []

        for row in rows:
            raw_path = row[pk_len]
            raw_status = row[pk_len + 1] if len(row) > pk_len + 1 else None
            if raw_status is None:
                continue
            sval = str(raw_status)
            means = status_means.get(sval)
            if means is None:
                continue
            if means == "TODO":
                todo_statuses.add(sval)
                todo_rows += 1
                continue
            has_path = raw_path is not None and bool(str(raw_path).strip())
            if not has_path:
                exists = False
            else:
                # Never touch the filesystem if the row path escapes `real_base`;
                # count the escaping path as a failure of `exists_per_status`.
                real_target = resolve_path_within_base(str(raw_path), real_base, path_cache)
                if real_target is None:
                    failed_count += 1
                    escaped_count += 1
                    if pk_len and not pii_redacted and len(sample_keys) < MAX_SAMPLE_KEYS:
                        sample_keys.append(_format_sample_key(tuple(row[:pk_len])))
                    continue
                exists = os.path.exists(real_target)
            if means == "present":
                present_compared += 1
                if not exists:
                    failed_count += 1
                    present_missing += 1
                    if pk_len and not pii_redacted and len(sample_keys) < MAX_SAMPLE_KEYS:
                        sample_keys.append(_format_sample_key(tuple(row[:pk_len])))
            elif means == "absent_expected":
                if not exists:
                    absent_expected_count += 1
                    absent_expected_statuses.add(sval)
            elif means == "absent_unexpected":
                failure_compared += 1
                if not exists:
                    failed_count += 1
                    unexpected_absent += 1
                    if pk_len and not pii_redacted and len(sample_keys) < MAX_SAMPLE_KEYS:
                        sample_keys.append(_format_sample_key(tuple(row[:pk_len])))

        passed = failed_count == 0
        absent_note = ""
        if absent_expected_count:
            statuses_str = ", ".join(sorted(absent_expected_statuses))
            absent_note = (
                f" ({absent_expected_count} rows absent as expected: "
                f"{statuses_str})"
            )
        if passed:
            msg = f"file existence matches status in {col_name!r}{absent_note}{s_suffix}"
        else:
            bits = []
            if present_missing:
                bits.append(f"{present_missing} 'present' row(s) missing on disk")
            if unexpected_absent:
                bits.append(
                    f"{unexpected_absent} 'absent_unexpected' row(s) missing on disk"
                )
            if escaped_count:
                bits.append(
                    f"{escaped_count} path(s) escape base {base_label!r}"
                )
            msg = "; ".join(bits) + absent_note + s_suffix

        return {
            "assertion": "exists_per_status",
            "target": col_name,
            "status": "passed" if passed else "failed",
            "rows_checked": len(rows),
            "failed_count": failed_count,
            "sample_keys": sample_keys,
            "pii_redacted": pii_redacted,
            "message": msg,
            "details": {
                "present_missing": present_missing,
                "absent_unexpected": unexpected_absent,
                "escaped_count": escaped_count,
                "absent_expected_count": absent_expected_count,
                "absent_expected_statuses": sorted(absent_expected_statuses),
                "unconfirmed_todo_statuses": sorted(todo_statuses),
                "unconfirmed_todo_rows": todo_rows,
                "present_compared": present_compared,
                "compared": present_compared + failure_compared,
            },
            "provenance_note": prov_note,
        }

    if comp.assertion == "size_matches_disk":
        col_name = str(comp.target)
        unit = str(params["unit"])
        status_col = params.get("status_column")
        status_means = params.get("status_means") or {}
        failed_count = 0
        twin_counts: dict[str, int] = {}
        files_compared = 0
        sample_keys = []

        for row in rows:
            raw_path = row[pk_len]
            raw_size = row[pk_len + 1]
            if raw_path is None or raw_size is None:
                continue
            if not str(raw_path).strip() or not str(raw_size).strip():
                continue
            if status_col and len(row) > pk_len + 2 and row[pk_len + 2] is not None:
                means = status_means.get(str(row[pk_len + 2]))
                if means in ("absent_expected", "TODO"):
                    continue
            # Never call os.stat() on a path that escapes `real_base`
            real_target = resolve_path_within_base(str(raw_path), real_base, path_cache)
            if real_target is None or not os.path.isfile(real_target):
                continue
            files_compared += 1
            actual_bytes = os.stat(real_target).st_size
            res = check_size_matches_disk(str(raw_size), actual_bytes, unit)
            if not res["matches"]:
                failed_count += 1
                twin = res["matched_twin_unit"]
                if twin:
                    twin_counts[twin] = twin_counts.get(twin, 0) + 1
                if pk_len and not pii_redacted and len(sample_keys) < MAX_SAMPLE_KEYS:
                    sample_keys.append(_format_sample_key(tuple(row[:pk_len])))

        passed = failed_count == 0
        if passed:
            msg = (
                f"sizes in {col_name!r} ({unit}) match disk across "
                f"{files_compared} file(s){s_suffix}"
            )
        elif twin_counts:
            top_twin, twin_n = max(twin_counts.items(), key=lambda kv: kv[1])
            noun = "size matches" if twin_n == 1 else "sizes match"
            msg = f"{twin_n} {noun} {top_twin}, contract says {unit}"
            if failed_count > twin_n:
                other_n = failed_count - twin_n
                msg += f" ({other_n} other size mismatch(es))"
            msg += s_suffix
        else:
            msg = f"{failed_count} size(s) in {col_name!r} do not match disk ({unit}){s_suffix}"

        return {
            "assertion": "size_matches_disk",
            "target": col_name,
            "status": "passed" if passed else "failed",
            "rows_checked": files_compared,
            "failed_count": failed_count,
            "sample_keys": sample_keys,
            "pii_redacted": pii_redacted,
            "message": msg,
            "details": {
                "unit": unit,
                "files_compared": files_compared,
                "compared": files_compared,
                "twin_unit_matches": twin_counts,
            },
            "provenance_note": prov_note,
        }

    raise ValueError(f"unsupported filesystem assertion {comp.assertion!r}")


def _missing_columns(contract: dict, discovered: tuple[str, ...]) -> list[str]:
    """Key and declared columns the data doesn't have, in contract order."""
    have = {str(c).lower() for c in discovered}
    wanted: list[str] = []
    for entry in contract.get("keys") or []:
        wanted.extend(str(k) for k in (entry if isinstance(entry, list) else [entry]))
    cols = contract.get("columns")
    if isinstance(cols, dict):
        wanted.extend(str(c) for c in cols)
    out: list[str] = []
    for name in wanted:
        clean = A._clean_ident_part(name)
        if clean.lower() not in have and clean not in out:
            out.append(clean)
    return out


def _referenced_columns(comp: A.CompiledAssertion) -> set[str]:
    names: set[str] = set()
    for text in (comp.sql, comp.count_sql):
        if not text:
            continue
        stmt = A.assert_single_select(text, dialect=comp.dialect)
        names |= {c.name.lower() for c in stmt.find_all(exp.Column)}
    return names


def verify_contract(
    contract: dict,
    project_root: str,
    bases: dict | None = None,
    now: datetime | str | None = None,
    max_rows: int = DEFAULT_MAX_ROWS,
    max_bytes: int = DEFAULT_MAX_BYTES,
    write_evidence: bool = False,
) -> dict[str, Any]:
    """Run all compiled SQL and filesystem assertions for `contract`.

    Returns a deterministic report dictionary and optionally appends audit
    records to `<project_root>/.truequery/evidence.jsonl`.
    """
    now_dt = _parse_now(now)
    now_iso = now_dt.isoformat()
    dataset = str(contract.get("dataset") or contract.get("table"))
    prov = A._provenance_params(contract)
    kind = contract.get("kind") or "table"
    loc = contract.get("location") if isinstance(contract.get("location"), dict) else {}

    source_files: list[str] = []
    source_format: str | None = None
    dialect = "duckdb"
    relation = dataset

    con = None
    try:
        if kind == "files":
            source_format = str(loc.get("format") or "csv")
            _, resolved_files = expand_contract_files(contract, bases, project_root)
            if not resolved_files:
                raise VerificationError(
                    f"no files matched location.path {loc.get('path')!r}"
                )
            total_bytes = sum(os.stat(f).st_size for f in resolved_files)
            if total_bytes > max_bytes:
                raise VerificationError(
                    f"dataset {dataset!r} size ({total_bytes} bytes) exceeds "
                    f"max_bytes limit ({max_bytes} bytes)"
                )
            source_files = [P._rel(f, os.path.realpath(project_root)) for f in resolved_files]
            relation = A._clean_ident_part(dataset.split(".")[-1]) or "dataset"
            con = open_duckdb_for_files(resolved_files)
            _setup_duckdb_files_view(
                con, relation, source_format, resolved_files, contract
            )
            discovered_cols, physical_types = _describe_relation_columns_and_types(
                con, dialect, relation
            )
        else:
            db_rel = loc.get("database")
            if not db_rel:
                raise VerificationError(
                    f"table contract {dataset!r} has no local location.database"
                )
            if not contract_v2._is_safe_rel_path(str(db_rel)):
                raise VerificationError(
                    f"location.database {db_rel!r} must be a relative path "
                    "inside the project or declared base"
                )
            real_base = resolve_base_dir(loc.get("base"), bases, project_root)
            real_db = resolve_path_within_base(str(db_rel), real_base)
            where = loc.get("base") or "the project folder"
            if real_db is None and os.path.lexists(
                    os.path.join(real_base, str(db_rel))):
                raise VerificationError(
                    f"database file {db_rel} points outside {where} "
                    "(a link?), so nothing was read"
                )
            if real_db is None or not os.path.isfile(real_db):
                raise VerificationError(
                    f"database file {db_rel} isn't there (looked in {where})"
                )
            total_bytes = os.stat(real_db).st_size
            if total_bytes > max_bytes:
                raise VerificationError(
                    f"database {db_rel!r} size ({total_bytes} bytes) exceeds "
                    f"max_bytes limit ({max_bytes} bytes)"
                )
            source_files = [P._rel(real_db, os.path.realpath(project_root))]
            relation = str(loc.get("relation") or dataset)
            if str(db_rel).lower().endswith(".duckdb"):
                dialect = "duckdb"
                source_format = "duckdb"
                con = open_duckdb_database(real_db)
            else:
                dialect = "sqlite"
                source_format = "sqlite"
                con = open_sqlite_readonly(real_db)
            discovered_cols, physical_types = _describe_relation_columns_and_types(
                con, dialect, relation
            )
            if not discovered_cols:
                raise VerificationError(
                    f"table {relation!r} isn't in {db_rel}")

        cnt_select = exp.select(
            exp.func("COUNT", exp.Star()).as_(
                exp.to_identifier("total_rows", quoted=True))
        ).from_(A._quote_table(relation))
        cnt_sql = A._render_select(cnt_select, dialect=dialect)
        total_rows = int(_execute_single_select(con, cnt_sql, dialect)[0][0])
        sampled = total_rows > max_rows
        checked_rows = min(total_rows, max_rows) if sampled else total_rows

        compiled_list = A.compile_contract_assertions(
            contract,
            dialect=dialect,
            relation=relation,
            sample_limit=max_rows if sampled else None,
            all_columns=discovered_cols,
        )
        assertion_results: list[dict[str, Any]] = []
        findings: list[dict[str, Any]] = []
        evidence_records: list[dict[str, Any]] = []

        # A column the contract declares but the data doesn't have is a
        # finding in itself; the assertions that need it can't run, and
        # the rest still do. (JSON readers fill declared columns with
        # NULL, so this applies to CSV, Parquet and database tables.)
        missing = (_missing_columns(contract, discovered_cols)
                   if source_format not in ("json", "jsonl") else [])
        if missing:
            gone = {m.lower() for m in missing}
            compiled_list = [c for c in compiled_list
                             if not (_referenced_columns(c) & gone)]
            assertion_results.append({
                "assertion": "columns_present",
                "target": missing,
                "status": "failed",
                "rows_checked": checked_rows,
                "failed_count": len(missing),
                "sample_keys": [],
                "pii_redacted": False,
                "message": (
                    f"column(s) {', '.join(missing)} declared in the contract "
                    "are not in the data"),
                "details": {"missing": missing,
                            "found": list(discovered_cols)},
                "provenance_note": prov["provenance_note"],
            })

        for comp in compiled_list:
            if comp.kind == "sql":
                res = _run_sql_assertion(
                    con, comp, checked_rows, physical_types, source_format, now_dt
                )
            else:
                res = _run_filesystem_assertion(
                    con, comp, checked_rows, bases, project_root
                )
            assertion_results.append(res)

        for res in assertion_results:
            if res["status"] == "failed":
                f_msg = res["message"]
                if prov["provenance_note"]:
                    f_msg = f"{f_msg} {prov['provenance_note']}"
                findings.append({
                    "dataset": dataset,
                    "assertion": res["assertion"],
                    "target": res["target"],
                    "failed_count": res["failed_count"],
                    "sample_keys": res["sample_keys"],
                    "pii_redacted": res["pii_redacted"],
                    "message": f_msg,
                    "source_files": source_files,
                    "provenance_note": prov["provenance_note"],
                })
            evidence_records.append({
                "dataset": dataset,
                "assertion": res["assertion"],
                "target": res["target"],
                "status": res["status"],
                "source_files": source_files,
                "rows_checked": res["rows_checked"],
                "failed_count": res["failed_count"],
                "sample_keys": res["sample_keys"],
                "pii_redacted": res["pii_redacted"],
                "message": res["message"],
                "checked_at": now_iso,
                "contract_status": prov["contract_status"],
                "inferred_from": prov["inferred_from"],
                "provenance_note": prov["provenance_note"],
            })
    finally:
        if con is not None:
            con.close()

    if write_evidence and evidence_records:
        append_evidence(project_root, evidence_records)

    summary_bits = [
        r["message"]
        for r in assertion_results
        if r["status"] in ("passed", "not_verified")
    ]
    summary = (
        f"{dataset} ({len(source_files)} file(s), {total_rows} rows): "
        + (", ".join(summary_bits) if summary_bits else "checked")
    )
    if prov["provenance_note"]:
        summary += f" {prov['provenance_note']}"

    return {
        "dataset": dataset,
        "valid": len(findings) == 0,
        "contract_status": prov["contract_status"],
        "inferred_from": prov["inferred_from"],
        "provenance_note": prov["provenance_note"],
        "checked_at": now_iso,
        "source": {
            "kind": kind,
            "format": source_format,
            "files": source_files,
            "rows": total_rows,
            "bytes": total_bytes,
            "sampled": sampled,
        },
        "assertions": assertion_results,
        "findings": findings,
        "summary": summary,
        "evidence_records": evidence_records,
    }


def _runner_errors() -> tuple[type[BaseException], ...]:
    """Errors that mean "this dataset could not be read", not a bug: a
    missing or vanished file, an unreadable database, a file DuckDB can't
    parse, a relation that isn't there."""
    errs: list[type[BaseException]] = [
        VerificationError, DuckDBMissingError, OSError, sqlite3.Error,
        UnicodeDecodeError,
    ]
    import sys
    duckdb = sys.modules.get("duckdb")
    if duckdb is not None and isinstance(getattr(duckdb, "Error", None), type):
        errs.append(duckdb.Error)
    return tuple(errs)


def error_text(exc: BaseException) -> str:
    """A short, private description of why a dataset couldn't be read.

    DuckDB's messages can quote a line of the file, so for its errors only
    the category before the first colon is kept (`Invalid Input Error`).
    Our own errors and OS errors name paths, never values."""
    if isinstance(exc, (VerificationError, DuckDBMissingError)):
        return str(exc)
    if isinstance(exc, FileNotFoundError):
        name = os.path.basename(exc.filename) if exc.filename else "a file"
        return f"{name} disappeared while it was being read"
    if isinstance(exc, OSError):
        return f"couldn't read a file ({exc.strerror or type(exc).__name__})"
    if isinstance(exc, sqlite3.Error):
        first = str(exc).splitlines()[0] if str(exc) else type(exc).__name__
        return f"SQLite couldn't read it ({first})"
    if isinstance(exc, UnicodeDecodeError):
        return "a file isn't valid UTF-8 text"
    first = str(exc).splitlines()[0] if str(exc) else ""
    category = first.split(":", 1)[0].strip() if ":" in first else type(exc).__name__
    return f"the data reader couldn't read it ({category})"


def verify_project(
    project_root: str,
    datasets: list[str] | None = None,
    now: datetime | str | None = None,
    write_evidence: bool = False,
    max_rows: int = DEFAULT_MAX_ROWS,
    max_bytes: int = DEFAULT_MAX_BYTES,
) -> dict[str, Any]:
    """Verify all local datasets with valid contracts in `project_root`.

    One dataset that can't be read never stops the others: it is listed in
    `not_checked` with the reason (`reader_missing` when DuckDB isn't
    installed, else `error`). Tables with no local `location.database`
    (warehouse tables) are listed in `skipped`. `unknown` lists requested
    dataset names that have no valid contract."""
    config = P.load_config(project_root) or {}
    bases = config.get("bases") or {}
    contracts, invalid_contracts = P.load_contracts_reporting(project_root)
    wanted = {d.lower() for d in datasets} if datasets else None
    reader = duckdb_status()

    reports: list[dict[str, Any]] = []
    skipped: list[dict[str, str]] = []
    not_checked: list[dict[str, Any]] = []
    matched: set[str] = set()
    for t_key, contract in sorted(contracts.items()):
        ds_name = str(contract.get("dataset") or contract.get("table"))
        if wanted is not None:
            hits = {t_key, ds_name.lower()} & wanted
            if not hits:
                continue
            matched |= hits
        if not has_local_data(contract):
            skipped.append({
                "dataset": ds_name,
                "reason": "no location",
            })
            continue
        prov = A._provenance_params(contract)
        if needs_duckdb(contract) and not reader["installed"]:
            not_checked.append({
                "dataset": ds_name,
                "reason": "reader_missing",
                "message": (
                    f"the data reader is too old (DuckDB {reader['version']}; "
                    f"TrueQuery needs {DUCKDB_SPEC})" if reader["too_old"]
                    else "the data reader isn't installed"),
                "provenance_note": prov["provenance_note"],
            })
            continue
        try:
            reports.append(
                verify_contract(
                    contract,
                    project_root=project_root,
                    bases=bases,
                    now=now,
                    max_rows=max_rows,
                    max_bytes=max_bytes,
                    write_evidence=write_evidence,
                )
            )
        except _runner_errors() as exc:
            not_checked.append({
                "dataset": ds_name,
                "reason": ("reader_missing"
                           if isinstance(exc, DuckDBMissingError) else "error"),
                "message": error_text(exc),
                "detail": str(exc),
                "provenance_note": prov["provenance_note"],
            })

    unknown = sorted(wanted - matched) if wanted is not None else []
    return {
        "valid": all(r["valid"] for r in reports) and not invalid_contracts,
        "datasets": reports,
        "skipped": skipped,
        "not_checked": not_checked,
        "invalid_contracts": invalid_contracts,
        "unknown": unknown,
        "reader": reader,
    }
